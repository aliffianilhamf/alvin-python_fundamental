number_1 = 100 
number_2 = 50 

print("Lebih dari (>)")
hasil = number_1 > number_2
print(f"Hasil dari {number_1} > {number_2} = {hasil}")
number_3 = 100 
hasil = number_1 > number_3
print(f"Hasil dari {number_1} > {number_3} = {hasil}")

print("\nKurang dari (<)")
hasil = number_1 < number_2
print(f"Hasil dari {number_1} < {number_2} = {hasil}")
number_3 = 100
hasil = number_1 < number_3
print(f"Hasil dari {number_1} < {number_3} = {hasil}")

print("\nLebih dari sama dengan (>=)")
hasil = number_1 >= number_2
print(f"Hasil dari {number_1} >= {number_2} = {hasil}")
number_3 = 100
hasil = number_1 >= number_3
print(f"Hasil dari {number_1} >= {number_3} = {hasil}")

print("\nKurang dari sama dengan (<=)")
hasil = number_1 <= number_2
print(f"Hasil dari {number_1} <= {number_2} = {hasil}")
number_3 = 100
hasil = number_1 <= number_3
print(f"Hasil dari {number_1} <= {number_3} = {hasil}")

print("\nSama dengan (==)")
hasil = number_1 == number_2
print(f"Hasil dari {number_1} == {number_2} = {hasil}")
number_3 = 100
hasil = number_1 == number_3
print(f"Hasil dari {number_1} == {number_3} = {hasil}")

print("\nTidak sama dengan (!=)")
hasil = number_1 != number_2
print(f"Hasil dari {number_1} != {number_2} = {hasil}")
number_3 = 100
hasil = number_1 != number_3
print(f"Hasil dari {number_1} != {number_3} = {hasil}")